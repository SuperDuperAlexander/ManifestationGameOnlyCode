import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';

const url = process.argv[2] ?? 'http://localhost:5173/?debug';
const outDir = 'screenshots/imp-progress';
mkdirSync(outDir, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist', '--enable-unsafe-swiftshader'] });
const errors = [];
const check = (ok, message) => { if (!ok) throw new Error(message); };
const waitForWorld = (page) => page.waitForFunction(() => window.__lw.world() === 'inner' && !window.__lw.transitioning(), null, { timeout: 7000 });
const readProgress = (page) => page.evaluate(() => window.__lw.impBreathProgress());

try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 720 } });
  await context.addInitScript(() => localStorage.setItem('lw.lantern.save.v1', JSON.stringify({ beat: 6, flags: { bumped: true, sawImp: true } })));
  const page = await context.newPage();
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto(url, { waitUntil: 'load' });
  await page.waitForFunction(() => !!window.__lw);
  await page.locator('.ss-continue').click();
  await page.waitForFunction(() => !document.querySelector('.start-screen'));
  await page.evaluate(() => window.__lw.toggle());
  await waitForWorld(page);
  await page.evaluate(() => window.__lw.teleport(...Object.values(window.__lw.impPos())));
  await page.waitForTimeout(250);
  check(!(await readProgress(page)).visible, 'progress showed before the outside help was complete');
  check(await page.locator('.imp-breath-progress').isHidden(), 'progress showed before the outside help was complete');
  await page.evaluate(() => window.__lw.debugBreath());
  check((await readProgress(page)).count === 0, 'ineligible pre-help breath changed progress');
  check(await page.locator('.imp-breath-progress').isHidden(), 'ineligible pre-help breath displayed progress');
  await page.evaluate(() => window.__lw.clearSave());
  await page.close();
  await context.close();

  const helpedContext = await browser.newContext({ viewport: { width: 1280, height: 720 } });
  await helpedContext.addInitScript(() => localStorage.setItem('light-within-breath-preferences', JSON.stringify({ inhaleSeconds: 1, exhaleSeconds: 1 })));
  await helpedContext.addInitScript(() => localStorage.setItem('lw.lantern.save.v1', JSON.stringify({ beat: 7, flags: { bumped: true, sawImp: true, helped: true } })));
  const helped = await helpedContext.newPage();
  helped.on('pageerror', (e) => errors.push(e.message));
  helped.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await helped.goto(url, { waitUntil: 'load' });
  await helped.waitForFunction(() => !!window.__lw);
  await helped.locator('.ss-continue').click();
  await helped.waitForFunction(() => !document.querySelector('.start-screen'));
  await helped.evaluate(() => window.__lw.toggle());
  await waitForWorld(helped);
  await helped.waitForFunction(() => window.__lw.impBreathProgress().visible);
  const imp = await helped.evaluate(() => window.__lw.impPos());
  await helped.evaluate((p) => window.__lw.teleport(p.x + 2, p.z - 17), imp);
  await helped.waitForFunction(() => document.querySelector('.imp-breath-status')?.textContent === 'Come close to the imp to breathe together.');
  await helped.evaluate(() => window.__lw.debugBreath());
  check((await readProgress(helped)).count === 0, 'far-away breath incorrectly advanced progress');
  await helped.evaluate((p) => window.__lw.teleport(p.x + 2, p.z - 7), imp);
  await helped.waitForFunction(() => document.querySelector('.imp-breath-status')?.textContent === 'Stay close and breathe together.');
  check(await helped.locator('.imp-breath-count').textContent() === '0/3', 'initial counter is not 0/3');
  check(await helped.locator('.imp-breath-mark.filled').count() === 0, 'initial marks are already filled');

  await helped.keyboard.down('Space');
  await helped.waitForFunction(() => window.__lw.breathState() === 'inhale');
  await helped.waitForTimeout(1200);
  await helped.keyboard.up('Space');
  await helped.keyboard.down('Shift');
  await helped.waitForFunction(() => window.__lw.breathState() === 'exhale');
  await helped.waitForTimeout(1200);
  await helped.keyboard.up('Shift');
  await helped.waitForFunction(() => window.__lw.impBreathProgress().count === 1, null, { timeout: 3000 });
  await helped.waitForFunction(() => document.querySelector('.imp-breath-count')?.textContent === '1/3');
  check(await helped.locator('.imp-breath-mark.filled').count() === 1, 'one completed breath did not fill one mark');
  check((await helped.locator('.imp-breath-remaining').textContent()) === '2 full breaths remaining', 'remaining count is wrong after the real full breath');
  await helped.screenshot({ path: `${outDir}/desktop-1-of-3.png` });
  await helped.keyboard.press('KeyQ');
  await helped.waitForFunction(() => window.__lw.world() === 'outer' && !window.__lw.transitioning(), null, { timeout: 7000 });
  await helped.waitForFunction(() => document.querySelector('.imp-breath-progress')?.hidden === true);
  await helped.keyboard.press('KeyQ');
  await waitForWorld(helped);
  await helped.waitForFunction(() => document.querySelector('.imp-breath-count')?.textContent === '1/3');
  await helped.waitForFunction(() => window.__lw.impBreathProgress().count === 0, null, { timeout: 18000 });
  await helped.waitForFunction(() => document.querySelector('.imp-breath-count')?.textContent === '0/3');
  await helped.evaluate(() => window.__lw.debugBreath());
  await helped.waitForFunction(() => document.querySelector('.imp-breath-count')?.textContent === '1/3');
  await helped.evaluate(() => window.__lw.debugBreath());
  await helped.waitForFunction(() => document.querySelector('.imp-breath-count')?.textContent === '2/3');
  await helped.evaluate(() => window.__lw.debugBreath());
  await helped.waitForFunction(() => document.querySelector('.imp-breath-count')?.textContent === '3/3');
  check(await helped.locator('.imp-breath-mark.filled').count() === 3, 'three completed breaths did not fill all marks');
  check((await helped.locator('.imp-breath-status').textContent()).includes('flame'), 'completion status did not describe the existing flame transition');
  await helped.screenshot({ path: `${outDir}/desktop-3-of-3.png` });
  await helped.waitForFunction(() => window.__lw.flags().lanternRelit, null, { timeout: 5000 });
  await helped.waitForFunction(() => document.querySelector('.imp-breath-progress')?.hidden === true);

  const touchContext = await browser.newContext({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  await touchContext.addInitScript(() => localStorage.setItem('light-within-breath-preferences', JSON.stringify({ inhaleSeconds: 1, exhaleSeconds: 1 })));
  await touchContext.addInitScript(() => localStorage.setItem('lw.lantern.save.v1', JSON.stringify({ beat: 7, flags: { bumped: true, sawImp: true, helped: true } })));
  const touch = await touchContext.newPage();
  touch.on('pageerror', (e) => errors.push(e.message));
  touch.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await touch.goto(`${url}${url.includes('?') ? '&' : '?'}touch`, { waitUntil: 'load' });
  await touch.waitForFunction(() => !!window.__lw);
  await touch.locator('.ss-continue').click();
  await touch.waitForFunction(() => !document.querySelector('.start-screen'));
  await touch.evaluate(() => window.__lw.toggle());
  await waitForWorld(touch);
  await touch.waitForFunction(() => window.__lw.impBreathProgress().visible);
  const touchImp = await touch.evaluate(() => window.__lw.impPos());
  await touch.evaluate((p) => window.__lw.teleport(p.x + 2, p.z - 7), touchImp);
  await touch.waitForFunction(() => document.querySelector('.imp-breath-count')?.textContent === '0/3');
  const fits = async () => touch.locator('.imp-breath-progress').evaluate((el) => {
    const r = el.getBoundingClientRect();
    const others = [...document.querySelectorAll('.next-step-hint:not([hidden]), .breath-guide, .breath-button, .hand-button, .look-button')]
      .map((el) => el.getBoundingClientRect()).filter((q) => q.width > 0 && q.height > 0);
    const overlapsControl = others.some((q) => r.left < q.right && r.right > q.left && r.top < q.bottom && r.bottom > q.top);
    return r.left >= 0 && r.top >= 0 && r.right <= innerWidth && r.bottom <= innerHeight && !overlapsControl;
  });
  check(await fits(), 'portrait progress panel clips or overlaps an important control');
  await touch.screenshot({ path: `${outDir}/touch-portrait.png` });
  await touch.setViewportSize({ width: 915, height: 412 });
  await touch.waitForTimeout(150);
  check(await fits(), 'landscape progress panel clips or overlaps an important control');
  await touch.screenshot({ path: `${outDir}/touch-landscape.png` });
  check(!errors.length, `browser errors: ${errors.join(' | ')}`);
  console.log(`imp-progress: PASS; real breath 0→1, marks 0→1→2→3, panel hidden at lantern relight, touch portrait/landscape fit; screenshots=${outDir}; console errors=0`);
} finally {
  await browser.close();
}
